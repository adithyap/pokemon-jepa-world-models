        ("Bench 2", "Cryogonal", 100, ""),
        ("Bench 3", "Grimmsnarl", 100, ""),
        ("Bench 4", "Tauros Aqua", 100, ""),
        ("Bench 5", "Rotom Mow", 100, ""),
