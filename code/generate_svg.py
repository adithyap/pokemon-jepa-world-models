def main() -> None:
    global BLOG_PUBLIC, FIGURE_DIR
    parser = argparse.ArgumentParser()
    parser.add_argument("--figure-dir", default=str(FIGURE_DIR))
    parser.add_argument("--public-dir", default="")
    args = parser.parse_args()

    FIGURE_DIR = Path(args.figure_dir)
    BLOG_PUBLIC = Path(args.public_dir) if args.public_dir else None

    generate_arch_svg()
    generate_battle_state_schematic()
    generate_learning_target_svg()
    print("Generated jepa-arch.svg, pokemon-battle-state-schematic.svg, and pokemon-learning-target.svg")


if __name__ == "__main__":
    main()
