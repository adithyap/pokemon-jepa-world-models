#!/usr/bin/env python3
"""Generate lightweight SVG assets for the Pokemon JEPA blog post.

The diagrams are intentionally dependency-free so they can be regenerated in
the repo without a plotting stack. Result plots are generated by
run_pokemon_jepa_v3_study.py.
"""

from __future__ import annotations

import argparse
from html import escape
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
FIGURE_DIR = ROOT / "figures"
BLOG_PUBLIC: Path | None = None

INK = "#1f2933"
MUTED = "#5f6b7a"
LINE = "#cbd5e1"
BLUE = "#1f6feb"
BLUE_SOFT = "#eaf2ff"
GREEN = "#1f7a4d"
GREEN_SOFT = "#e8f6ef"
RED = "#b42318"
RED_SOFT = "#fff1f0"
GOLD = "#946200"
GOLD_SOFT = "#fff8df"
PANEL = "#f8fafc"


def write_svg(name: str, svg: str) -> None:
    FIGURE_DIR.mkdir(parents=True, exist_ok=True)
    roots = [FIGURE_DIR]
    if BLOG_PUBLIC is not None:
        BLOG_PUBLIC.mkdir(parents=True, exist_ok=True)
        roots.append(BLOG_PUBLIC)
    for root in roots:
        (root / name).write_text(svg, encoding="utf-8")


def text(x: float, y: float, value: str, *, size: int = 14, weight: str = "400",
         fill: str = INK, anchor: str = "middle", family: str = "Inter, Arial, sans-serif") -> str:
    return (
        f'<text x="{x}" y="{y}" text-anchor="{anchor}" '
        f'font-family="{family}" font-size="{size}" font-weight="{weight}" '
        f'fill="{fill}">{escape(value)}</text>'
    )


def multiline(x: float, y: float, lines: list[str], *, size: int = 13,
              weight: str = "400", fill: str = MUTED, anchor: str = "middle",
              line_height: int = 18) -> str:
    return "\n".join(
        text(x, y + i * line_height, line, size=size, weight=weight, fill=fill, anchor=anchor)
        for i, line in enumerate(lines)
    )


def box(x: float, y: float, w: float, h: float, *, fill: str, stroke: str,
        radius: int = 10, sw: int = 2) -> str:
    return (
        f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{radius}" '
        f'fill="{fill}" stroke="{stroke}" stroke-width="{sw}" />'
    )


def arrow(x1: float, y1: float, x2: float, y2: float, *, stroke: str = "#64748b") -> str:
    return (
        f'<path d="M {x1} {y1} L {x2} {y2}" stroke="{stroke}" '
        'stroke-width="2.5" fill="none" marker-end="url(#arrowhead)" />'
    )


def hp_bar(x: float, y: float, w: float, hp: int, *, color: str = BLUE) -> str:
    fill_w = max(0, min(w, w * hp / 100))
    return (
        f'<rect x="{x}" y="{y}" width="{w}" height="7" rx="3.5" fill="#e2e8f0" />'
        f'<rect x="{x}" y="{y}" width="{fill_w}" height="7" rx="3.5" fill="{color}" />'
    )


def token_card(x: float, y: float, w: float, h: float, slot: str, name: str, hp: int,
               note: str = "", *, active: bool = False, fainted: bool = False) -> str:
    stroke = BLUE if active else LINE
    fill = "#ffffff" if not fainted else "#f1f5f9"
    name_lines = name.split(" ")
    out = [
        box(x, y, w, h, fill=fill, stroke=stroke, radius=8, sw=2 if active else 1),
        text(x + 12, y + 21, slot, size=11, weight="800", fill=BLUE if active else MUTED, anchor="start"),
    ]
    for i, line in enumerate(name_lines[:2]):
        out.append(text(x + w / 2, y + 48 + i * 15, line, size=13, weight="800", fill=INK))
    out.append(text(x + w / 2, y + 86, f"HP {hp}%", size=12, weight="800", fill=BLUE))
    out.append(hp_bar(x + 14, y + 96, w - 28, hp, color=RED if hp <= 25 else BLUE))
    if note:
        out.append(text(x + w / 2, y + h - 15, note, size=10, fill=MUTED))
    return "\n".join(out)


def defs() -> str:
    return """<defs>
  <marker id="arrowhead" markerWidth="10" markerHeight="8" refX="9" refY="4" orient="auto">
    <polygon points="0 0, 10 4, 0 8" fill="#64748b" />
  </marker>
</defs>"""


